def _mfds(reference_days):
    """식약처 소비기한 참고값은 제조일 기준이라, 구입일 기준으로는 80%(내림)에서 빨강, 그 3일 전부터 노랑."""
    danger = reference_days * 8 // 10
    return danger - 3, danger


