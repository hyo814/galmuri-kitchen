from .matching import normalize

# 장보기에는 담지만 재고(냉장고)에는 넣지 않는 생활용품(스펙 16절, 2026-09-14 사용자 결정)
KEYWORDS = (
    "수세미", "휴지", "두루마리", "키친타월", "물티슈", "세제", "섬유유연제", "락스", "샴푸", "린스", "바디워시",
    "치약", "칫솔", "비누", "랩", "호일", "지퍼백", "위생장갑", "고무장갑", "쓰레기봉투", "건전지", "행주", "수건",
)


def is_household(name):
    """이름으로 생활용품인지 짐작한다. 두 글자 이상 낱말은 들어 있기만 해도(`주방세제`·`쿠킹호일`), 한 글자(`랩`)는 이름 전체가 같을 때만(`크랩` 제외).
    ponytail: 낱말 목록 짐작이라 `수세미오이` 같은 식품도 생활용품으로 볼 수 있다 — 재고에 넣기 화면에서 줄마다 켜고 끌 수 있다. 틀림이 잦으면 목록을 늘린다."""
    key = normalize(name)
    return any(key == word or (len(word) > 1 and word in key) for word in KEYWORDS)
